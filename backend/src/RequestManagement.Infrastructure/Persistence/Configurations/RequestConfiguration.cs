using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using RequestManagement.Core.Domain;

namespace RequestManagement.Infrastructure.Persistence.Configurations;

internal sealed class RequestConfiguration : IEntityTypeConfiguration<Request>
{
    public void Configure(EntityTypeBuilder<Request> builder)
    {
        builder.ToTable("Requests", table =>
        {
            table.HasCheckConstraint("CK_Requests_Status", "[Status] BETWEEN 1 AND 4");
            table.HasCheckConstraint("CK_Requests_Priority", "[Priority] BETWEEN 1 AND 3");
            table.HasCheckConstraint("CK_Requests_UpdatedAt_NotBeforeCreatedAt", "[UpdatedAt] >= [CreatedAt]");
        });

        builder.HasKey(r => r.Id);

        builder.Property(r => r.Title).HasMaxLength(Request.TitleMaxLength);
        builder.Property(r => r.OrganizationName).HasMaxLength(Request.OrganizationNameMaxLength);
        builder.Property(r => r.AssignedTo).HasMaxLength(Request.AssignedToMaxLength);

        // SQL Server rowversion: generated by the database on insert and on every update,
        // and used by EF Core in the WHERE clause of UPDATE statements.
        builder.Property(r => r.Version).IsRowVersion();

        builder.HasMany(r => r.StatusHistory)
            .WithOne(h => h.Request)
            .HasForeignKey(h => h.RequestId)
            .OnDelete(DeleteBehavior.Restrict); // audit rows must never disappear with their request

        // Secondary indexes for the planned list/aggregation queries (plan §4.3, decision D14).
        // They belong to the AddQueryIndexes migration and are measured before/after in Phase 5;
        // an index that shows no benefit there is dropped.

        // Default sort (CreatedAt DESC, Id DESC tie-breaker), date range filter, deep pages (B1b).
        builder.HasIndex(r => new { r.CreatedAt, r.Id }, "IX_Requests_CreatedAt_Id")
            .IsDescending(true, true);

        // Status filter with the default sort; GROUP BY Status for the summary (B1a, B2).
        builder.HasIndex(r => new { r.Status, r.CreatedAt }, "IX_Requests_Status_CreatedAt")
            .IsDescending(false, true)
            .IncludeProperties(r => r.Priority);

        // A handler's queue: AssignedTo (exact) + optional Status, newest first.
        builder.HasIndex(r => new { r.AssignedTo, r.Status, r.CreatedAt }, "IX_Requests_AssignedTo_Status_CreatedAt")
            .IsDescending(false, false, true);

        // OrganizationName starts-with filter (sargable LIKE 'prefix%'), newest first.
        builder.HasIndex(r => new { r.OrganizationName, r.CreatedAt }, "IX_Requests_OrganizationName_CreatedAt")
            .IsDescending(false, true);

        // GROUP BY Priority for the summary (B2) from a narrow index instead of the clustered index.
        builder.HasIndex(r => new { r.Priority, r.Status }, "IX_Requests_Priority_Status");
    }
}
