using System.Data;
using Microsoft.Data.SqlClient;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Storage;
using RequestManagement.Core.Domain;
using RequestManagement.Infrastructure.Persistence;

namespace RequestManagement.Infrastructure.Seeding;

/// <summary>
/// Loads generated test data into SQL Server. Shared by the Seeder console and the tests.
/// </summary>
/// <remarks>
/// Rows are streamed from <see cref="SeedDataGenerator"/> into a reusable <see cref="DataTable"/>
/// of at most <see cref="SeedOptions.BatchSize"/> rows, written with <see cref="SqlBulkCopy"/>,
/// then cleared, so memory use depends on the batch size and not on the total count.
/// </remarks>
public sealed class DatabaseSeeder(AppDbContext db)
{
    // Business columns written by the seeder. Version (rowversion) is generated by SQL Server.
    private static readonly (string Property, Type ClrType, Func<Request, object?> GetValue)[] Columns =
    [
        (nameof(Request.Id), typeof(int), r => r.Id),
        (nameof(Request.Title), typeof(string), r => r.Title),
        (nameof(Request.OrganizationName), typeof(string), r => r.OrganizationName),
        (nameof(Request.Status), typeof(byte), r => (byte)r.Status),
        (nameof(Request.Priority), typeof(byte), r => (byte)r.Priority),
        (nameof(Request.AssignedTo), typeof(string), r => r.AssignedTo),
        (nameof(Request.CreatedAt), typeof(DateTime), r => r.CreatedAt),
        (nameof(Request.UpdatedAt), typeof(DateTime), r => r.UpdatedAt),
    ];

    /// <summary>
    /// DESTRUCTIVE: drops the database in the connection string and recreates it from the
    /// migrations. Callers are responsible for restricting this to development databases.
    /// </summary>
    public async Task ResetDatabaseAsync(CancellationToken cancellationToken)
    {
        await db.Database.EnsureDeletedAsync(cancellationToken);
        await db.Database.MigrateAsync(cancellationToken);
    }

    /// <summary>
    /// Inserts <see cref="SeedOptions.Count"/> generated requests in one transaction.
    /// Refuses to run if the schema is not fully migrated or if data already exists,
    /// so it can never append duplicates or overwrite anything.
    /// </summary>
    /// <returns>The number of rows inserted.</returns>
    public async Task<int> SeedAsync(SeedOptions options, IProgress<int>? progress, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(options);
        options.Validate();
        await EnsureReadyForSeedingAsync(cancellationToken);

        var table = RequestsTable.From(db);

        await using var transaction = await db.Database.BeginTransactionAsync(cancellationToken);
        var connection = (SqlConnection)db.Database.GetDbConnection();

        // KeepIdentity: the generator's Ids (1..N) are stored as-is, so Ids are deterministic.
        // CheckConstraints: without it SqlBulkCopy skips CHECK constraints and marks them untrusted.
        // TableLock: allows minimally logged bulk inserts into the empty table.
        using var bulkCopy = new SqlBulkCopy(
            connection,
            SqlBulkCopyOptions.KeepIdentity | SqlBulkCopyOptions.CheckConstraints | SqlBulkCopyOptions.TableLock,
            (SqlTransaction)transaction.GetDbTransaction())
        {
            DestinationTableName = table.QualifiedName,
            BatchSize = options.BatchSize,
            BulkCopyTimeout = 0, // bounded by the cancellation token instead
        };

        using var batch = new DataTable();
        foreach (var (property, clrType, _) in Columns)
        {
            var column = table.ColumnName(property);
            batch.Columns.Add(column, clrType);
            bulkCopy.ColumnMappings.Add(column, column);
        }

        var inserted = 0;
        var values = new object[Columns.Length];
        foreach (var request in SeedDataGenerator.Generate(options))
        {
            for (var i = 0; i < Columns.Length; i++)
            {
                values[i] = Columns[i].GetValue(request) ?? DBNull.Value;
            }

            batch.Rows.Add(values);
            if (batch.Rows.Count == options.BatchSize)
            {
                inserted += await FlushAsync(bulkCopy, batch, cancellationToken);
                progress?.Report(inserted);
            }
        }

        if (batch.Rows.Count > 0)
        {
            inserted += await FlushAsync(bulkCopy, batch, cancellationToken);
            progress?.Report(inserted);
        }

        await transaction.CommitAsync(cancellationToken);
        return inserted;
    }

    public async Task<SeedReport> GetReportAsync(CancellationToken cancellationToken)
    {
        var requestCount = await db.Requests.LongCountAsync(cancellationToken);
        var historyCount = await db.RequestStatusHistory.LongCountAsync(cancellationToken);

        var byStatus = await db.Requests
            .GroupBy(r => r.Status)
            .Select(g => new { g.Key, Count = g.Count() })
            .ToDictionaryAsync(x => x.Key, x => x.Count, cancellationToken);

        var byPriority = await db.Requests
            .GroupBy(r => r.Priority)
            .Select(g => new { g.Key, Count = g.Count() })
            .ToDictionaryAsync(x => x.Key, x => x.Count, cancellationToken);

        var table = RequestsTable.From(db);
        var checksumColumns = string.Join(", ", Columns.Select(c => $"[{table.ColumnName(c.Property)}]"));
#pragma warning disable EF1002 // Identifiers come from the EF model, not from user input.
        var checksum = await db.Database
            .SqlQueryRaw<int?>($"SELECT CHECKSUM_AGG(CHECKSUM({checksumColumns})) AS [Value] FROM {table.QualifiedName}")
            .SingleAsync(cancellationToken);
#pragma warning restore EF1002

        return new SeedReport(requestCount, historyCount, byStatus, byPriority, checksum);
    }

    private async Task EnsureReadyForSeedingAsync(CancellationToken cancellationToken)
    {
        var pending = (await db.Database.GetPendingMigrationsAsync(cancellationToken)).ToList();
        if (pending.Count > 0)
        {
            throw new InvalidOperationException(
                $"The database schema is not up to date (pending migrations: {string.Join(", ", pending)}). " +
                "Apply them with 'dotnet ef database update' or use --reset.");
        }

        if (await db.Requests.AnyAsync(cancellationToken) || await db.RequestStatusHistory.AnyAsync(cancellationToken))
        {
            throw new InvalidOperationException(
                "The database already contains data. Seeding never appends to or overwrites existing data; " +
                "use --reset to drop and regenerate the development database.");
        }
    }

    private static async Task<int> FlushAsync(SqlBulkCopy bulkCopy, DataTable batch, CancellationToken cancellationToken)
    {
        await bulkCopy.WriteToServerAsync(batch, cancellationToken);
        var written = batch.Rows.Count;
        batch.Clear();
        return written;
    }

    /// <summary>Table and column names taken from the EF model, so they cannot drift from the mapping.</summary>
    private sealed class RequestsTable
    {
        private readonly IEntityType _entityType;

        private RequestsTable(IEntityType entityType)
        {
            _entityType = entityType;
            QualifiedName = $"[{entityType.GetSchema() ?? "dbo"}].[{entityType.GetTableName()}]";
        }

        public string QualifiedName { get; }

        public static RequestsTable From(AppDbContext db) =>
            new(db.Model.FindEntityType(typeof(Request))
                ?? throw new InvalidOperationException("Request is not part of the EF model."));

        public string ColumnName(string property) =>
            _entityType.FindProperty(property)?.GetColumnName()
            ?? throw new InvalidOperationException($"Property '{property}' is not mapped.");
    }
}
