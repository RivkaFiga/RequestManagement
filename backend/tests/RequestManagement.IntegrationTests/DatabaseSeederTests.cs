using Microsoft.EntityFrameworkCore;
using RequestManagement.Core.Domain;
using RequestManagement.Infrastructure.Persistence;
using RequestManagement.Infrastructure.Seeding;

namespace RequestManagement.IntegrationTests;

/// <summary>
/// Seeding, reset and schema behaviour against a real SQL Server.
/// Every test starts from a reset database, so tests do not depend on each other.
/// </summary>
[Collection(SqlServerCollection.Name)]
public sealed class DatabaseSeederTests(SqlServerFixture fixture)
{
    private static readonly SeedOptions SmallSeed = new() { Count = 2_500, BatchSize = 1_000 };

    [Fact]
    public async Task Seed_WritesExactlyTheGeneratedRows_InBatches()
    {
        await ResetAsync();
        var progress = new List<int>();

        await using (var db = fixture.CreateContext())
        {
            var inserted = await new DatabaseSeeder(db).SeedAsync(SmallSeed, new SyncProgress(progress), CancellationToken.None);
            Assert.Equal(SmallSeed.Count, inserted);
        }

        // 2,500 rows with batch size 1,000 => three flushes.
        Assert.Equal(new[] { 1_000, 2_000, 2_500 }, progress);

        await using var verify = fixture.CreateContext();
        var stored = await verify.Requests.AsNoTracking().OrderBy(r => r.Id).ToListAsync();
        var expected = SeedDataGenerator.Generate(SmallSeed).ToList();

        Assert.Equal(expected.Count, stored.Count);
        for (var i = 0; i < expected.Count; i++)
        {
            Assert.Equal(Fingerprint(expected[i]), Fingerprint(stored[i]));
            Assert.Equal(DateTimeKind.Utc, stored[i].CreatedAt.Kind);
            Assert.Equal(8, stored[i].Version.Length); // rowversion generated by SQL Server
        }
    }

    [Fact]
    public async Task ResetAndReseed_IsRepeatable_AndIndependentOfBatchSize()
    {
        var first = await ResetSeedAndReportAsync(SmallSeed with { BatchSize = 500 });
        var second = await ResetSeedAndReportAsync(SmallSeed with { BatchSize = 2_500 });

        Assert.Equal(SmallSeed.Count, first.RequestCount);
        Assert.Equal(first.RequestCount, second.RequestCount);
        Assert.Equal(0, second.HistoryCount);
        Assert.NotNull(first.Checksum);
        Assert.Equal(first.Checksum, second.Checksum);
        Assert.Equal(first.ByStatus, second.ByStatus);
        Assert.Equal(first.ByPriority, second.ByPriority);
        Assert.Equal(first.RequestCount, first.ByStatus.Values.Sum());
    }

    [Fact]
    public async Task Seed_RefusesToAppendToExistingData()
    {
        await ResetSeedAndReportAsync(SmallSeed);

        await using var db = fixture.CreateContext();
        var error = await Assert.ThrowsAsync<InvalidOperationException>(
            () => new DatabaseSeeder(db).SeedAsync(SmallSeed, null, CancellationToken.None));

        Assert.Contains("--reset", error.Message);
        Assert.Equal(SmallSeed.Count, await db.Requests.CountAsync());
    }

    [Fact]
    public async Task Seed_RefusesAnUnmigratedDatabase()
    {
        await using var db = fixture.CreateContext();
        await db.Database.EnsureDeletedAsync();

        var error = await Assert.ThrowsAsync<InvalidOperationException>(
            () => new DatabaseSeeder(db).SeedAsync(SmallSeed, null, CancellationToken.None));

        Assert.Contains("pending migrations", error.Message);
    }

    [Fact]
    public async Task BulkCopy_LeavesConstraintsTrusted_AndIdentityContinuesAfterSeededIds()
    {
        await ResetSeedAndReportAsync(SmallSeed);
        await using var db = fixture.CreateContext();

        var untrusted = await db.Database
            .SqlQueryRaw<int>("SELECT COUNT(*) AS [Value] FROM sys.check_constraints WHERE is_not_trusted = 1 OR is_disabled = 1")
            .SingleAsync();
        Assert.Equal(0, untrusted);

        var request = NewRequest();
        db.Requests.Add(request);
        await db.SaveChangesAsync();
        Assert.Equal(SmallSeed.Count + 1, request.Id);
    }

    [Fact]
    public async Task Version_ChangesOnEveryUpdate()
    {
        await ResetAsync();
        await using var db = fixture.CreateContext();
        var request = NewRequest();
        db.Requests.Add(request);
        await db.SaveChangesAsync();
        var original = request.Version;

        request.Status = RequestStatus.InProgress;
        request.UpdatedAt = request.UpdatedAt.AddMinutes(1);
        await db.SaveChangesAsync();

        Assert.NotEqual(original, request.Version);
    }

    [Fact]
    public async Task Constraints_RejectInvalidRows()
    {
        await ResetAsync();

        // Undefined status value.
        await AssertRejectedAsync(db => db.Requests.Add(NewRequest(status: (RequestStatus)9)));

        // UpdatedAt before CreatedAt.
        await AssertRejectedAsync(db =>
        {
            var request = NewRequest();
            request.UpdatedAt = request.CreatedAt.AddSeconds(-1);
            db.Requests.Add(request);
        });

        // History row for a request that does not exist.
        await AssertRejectedAsync(db => db.RequestStatusHistory.Add(NewHistory(requestId: 999_999)));

        // History row that does not change the status.
        int existingId;
        await using (var db = fixture.CreateContext())
        {
            var request = NewRequest();
            db.Requests.Add(request);
            await db.SaveChangesAsync();
            existingId = request.Id; // failed inserts above consumed identity values
        }

        await AssertRejectedAsync(db =>
        {
            var history = NewHistory(existingId);
            history.NewStatus = history.PreviousStatus;
            db.RequestStatusHistory.Add(history);
        });
    }

    [Fact]
    public async Task Request_WithHistory_CannotBeDeleted()
    {
        await ResetAsync();
        await using (var db = fixture.CreateContext())
        {
            var request = NewRequest();
            request.StatusHistory.Add(NewHistory(requestId: 0));
            db.Requests.Add(request);
            await db.SaveChangesAsync();
        }

        await using var verify = fixture.CreateContext();
        var stored = await verify.Requests.SingleAsync();
        verify.Requests.Remove(stored);

        await Assert.ThrowsAsync<DbUpdateException>(() => verify.SaveChangesAsync());
    }

    private async Task ResetAsync()
    {
        await using var db = fixture.CreateContext();
        await new DatabaseSeeder(db).ResetDatabaseAsync(CancellationToken.None);
    }

    private async Task<SeedReport> ResetSeedAndReportAsync(SeedOptions options)
    {
        await using var db = fixture.CreateContext();
        var seeder = new DatabaseSeeder(db);
        await seeder.ResetDatabaseAsync(CancellationToken.None);
        await seeder.SeedAsync(options, null, CancellationToken.None);
        return await seeder.GetReportAsync(CancellationToken.None);
    }

    private async Task AssertRejectedAsync(Action<AppDbContext> addInvalidRow)
    {
        await using var db = fixture.CreateContext();
        addInvalidRow(db);
        await Assert.ThrowsAsync<DbUpdateException>(() => db.SaveChangesAsync());
    }

    private static Request NewRequest(RequestStatus status = RequestStatus.New)
    {
        var now = new DateTime(2026, 10, 1, 12, 0, 0, DateTimeKind.Utc);
        return new Request
        {
            Title = "Integration test request",
            OrganizationName = "Test Organization",
            Status = status,
            Priority = RequestPriority.Medium,
            CreatedAt = now,
            UpdatedAt = now,
        };
    }

    private static RequestStatusHistoryEntry NewHistory(int requestId) => new()
    {
        RequestId = requestId,
        PreviousStatus = RequestStatus.New,
        NewStatus = RequestStatus.InProgress,
        ChangedAt = new DateTime(2026, 10, 1, 12, 5, 0, DateTimeKind.Utc),
        ChangedBy = "integration-test",
    };

    private static string Fingerprint(Request r) =>
        $"{r.Id}|{r.Title}|{r.OrganizationName}|{r.Status}|{r.Priority}|{r.AssignedTo}|{r.CreatedAt:O}|{r.UpdatedAt:O}";

    /// <summary><see cref="Progress{T}"/> posts asynchronously; this records synchronously.</summary>
    private sealed class SyncProgress(List<int> values) : IProgress<int>
    {
        public void Report(int value) => values.Add(value);
    }
}
